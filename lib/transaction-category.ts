const normalize = (text: string) =>
  text
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[^\p{L}\p{M}\p{N}]+/gu, ' ')
    .trim();

/** Phrases go through the same normalisation as titles, so a nukta matches either way it was typed. */
const prepare = (rules: CategoryRule[]) =>
  rules.map((rule) => ({ category: rule.category, phrases: rule.phrases.map(normalize) }));

const preparedExpenseRules = prepare(expenseRules);
const preparedIncomeRules = prepare(incomeRules);

/** Whole words only, so "Metropolis" is not the metro; a plural "s"/"es" is allowed on the last word. */
const containsPhrase = (normalizedTitle: string, phrase: string) =>
  normalizedTitle.includes(` ${phrase} `) ||
  normalizedTitle.includes(` ${phrase}s `) ||
  normalizedTitle.includes(` ${phrase}es `);

/** Local hints only: unknown or equally specific conflicting clues stay uncategorized. */
export function inferTransactionCategory(title: string, type: string): Category | null {
  const normalized = ` ${normalize(title)} `;
  const rules = type.toLowerCase() === 'income' ? preparedIncomeRules : preparedExpenseRules;
  let category: Category | null = null;
  let bestScore = 0;
  for (const rule of rules) {
    const score = rule.phrases.reduce(
      (best, phrase) =>
        containsPhrase(normalized, phrase) ? Math.max(best, phrase.split(' ').length) : best,
      0
    );
    if (score > bestScore) {
      category = rule.category;
      bestScore = score;
    } else if (score > 0 && score === bestScore) {
      category = null;
    }
  }
  return category;
}
